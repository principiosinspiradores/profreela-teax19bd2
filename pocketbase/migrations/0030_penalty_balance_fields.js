// Adds the fields powering the "professional delay penalty + automatic debit"
// flow (Entrega 2) to the `users` and `jobs` collections.
//
// New fields:
//   users:
//     - penalty_balance (number, default 0) — outstanding debtor balance for a
//       professional who caused a delay-driven cancel+reopen. Always >= 0.
//       Incremented when a delay-driven emergency reopen is created
//       (emergencyCost = price * 0.2); decremented as escrow payouts are
//       released; zeroed when an admin forgives the debit.
//
//   jobs:
//     - penalty_applied   (bool, default false) — this job generated a penalty
//       debit against its pro (delay-driven cancel+reopen).
//     - penalty_forgiven  (bool, default false) — admin forgave the debit
//       generated by this job (the balance was zeroed out).
//
// Note: `jobs.penalty_amount` already exists (added in 0013, used by the
// generic cancel_job.js for the cancellation fee). In the delay-driven
// cancel+reopen context it stores the emergency cost (price * 0.2) debited from
// the late pro. The field is reused — no new column needed for the amount.
//
// Notes:
//   - All bool fields are intentionally NOT `required`. A required bool rejects
//     every create that sends false/omits the field (PocketBase treats false as
//     the empty value). Absent → treated as false/null by the hooks.
//   - `users` is an auth collection; created/updated are included automatically.
migrate(
  (app) => {
    // --- users.penalty_balance ---
    const usersCol = app.findCollectionByNameOrId('users')
    if (!usersCol.fields.getByName('penalty_balance')) {
      usersCol.fields.add(new NumberField({ name: 'penalty_balance', required: false }))
    }
    app.save(usersCol)

    // Backfill existing rows to 0 so reads/hooks always see a number (defensive —
    // number fields default to NULL on existing rows until set).
    try {
      app
        .db()
        .newQuery('UPDATE users SET penalty_balance = 0 WHERE penalty_balance IS NULL')
        .execute()
    } catch (_) {}

    // --- jobs.penalty_applied / penalty_forgiven ---
    const jobsCol = app.findCollectionByNameOrId('jobs')
    if (!jobsCol.fields.getByName('penalty_applied')) {
      jobsCol.fields.add(new BoolField({ name: 'penalty_applied', required: false }))
    }
    if (!jobsCol.fields.getByName('penalty_forgiven')) {
      jobsCol.fields.add(new BoolField({ name: 'penalty_forgiven', required: false }))
    }
    app.save(jobsCol)
  },
  (app) => {
    const usersCol = app.findCollectionByNameOrId('users')
    const ub = usersCol.fields.getByName('penalty_balance')
    if (ub) usersCol.fields.remove(ub)
    app.save(usersCol)

    const jobsCol = app.findCollectionByNameOrId('jobs')
    ;['penalty_applied', 'penalty_forgiven'].forEach((name) => {
      const f = jobsCol.fields.getByName(name)
      if (f) jobsCol.fields.remove(f)
    })
    app.save(jobsCol)
  },
)
